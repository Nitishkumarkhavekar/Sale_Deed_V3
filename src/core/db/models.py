class User(Base):
    __tablename__ = "users"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    username: Mapped[str] = mapped_column(String(150), unique=True, nullable=False)
    created_at: Mapped[datetime] = mapped_column(TS, server_default=func.now(),
                                                 nullable=False)

    batches: Mapped[list[Batch]] = relationship(back_populates="user")


class Batch(Base):
    __tablename__ = "batches"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    user_id: Mapped[int | None] = mapped_column(ForeignKey("users.id"), index=True)

    state: Mapped[BatchState] = mapped_column(
        _enum(BatchState, "batch_state"), default=BatchState.QUEUED, nullable=False)
    #: Position in the queue. At most 4 batches may be queued at once; enforced in
    #: the repository rather than by a constraint so the error can explain itself.
    queue_position: Mapped[int] = mapped_column(Integer, default=0, nullable=False)

    file_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    total_bytes: Mapped[int] = mapped_column(BigInteger, default=0, nullable=False)

    created_at: Mapped[datetime] = mapped_column(TS, server_default=func.now(),
                                                 nullable=False, index=True)
    started_at: Mapped[datetime | None] = mapped_column(TS)
    finished_at: Mapped[datetime | None] = mapped_column(TS)

    user: Mapped[User | None] = relationship(back_populates="batches")
    documents: Mapped[list[Document]] = relationship(
        back_populates="batch", cascade="all, delete-orphan",
        passive_deletes=True)

    __table_args__ = (
        CheckConstraint("file_count >= 0", name="file_count_non_negative"),
        CheckConstraint("total_bytes >= 0", name="total_bytes_non_negative"),
        Index("ix_batches_state_position", "state", "queue_position"),
    )


class Document(Base):
    """The resume unit. One row per PDF."""

    __tablename__ = "documents"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    batch_id: Mapped[int] = mapped_column(ForeignKey("batches.id", ondelete="CASCADE"),
                                         nullable=False)
    #: Internal handle for this document within its batch. Seeded from the file
    #: name at upload because the row has to exist and be addressable before
    #: anything has been read - it is NOT NULL and unique per batch, and
    #: `add_many` drops an entry without one.
    #:
    #: **This is not the Transaction Identity.** It used to be used as one, so a
    #: deed whose registration number could not be read exported its file name
    #: instead - see `transaction_identity` below and R-043.
    document_id: Mapped[str] = mapped_column(String(100), nullable=False)
    #: The registration number read off the deed itself, e.g.
    #: "BGP-1-00275-2025-26". NULL until extraction finds one, and it stays NULL
    #: when nothing convincing is there: the export must show an empty cell
    #: rather than a value that might belong to a previous owner.
    transaction_identity: Mapped[str | None] = mapped_column(String(100))
    #: How sure the extractor was. Kept so an operator can see why a cell is
    #: blank, and so a low-confidence run can be reviewed rather than trusted.
    transaction_identity_confidence: Mapped[float | None] = mapped_column(Float)
    source_filename: Mapped[str] = mapped_column(String(500), nullable=False)
    #: Path only. Rendered page images are never stored in the database.
    source_path: Mapped[str | None] = mapped_column(String(1000))
    #: The prepared copy: separable overlays removed, text layer guaranteed.
    #: Everything downstream reads this when it is set, so there is one notion
    #: of "the document". The original is never modified and stays the record.
    cleaned_path: Mapped[str | None] = mapped_column(String(1000))
    page_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    size_bytes: Mapped[int] = mapped_column(BigInteger, default=0, nullable=False)

    # Per-stage state is what makes resume possible.
    ocr_state: Mapped[StageState] = mapped_column(
        _enum(StageState, "stage_state"), default=StageState.PENDING, nullable=False)
    extract_state: Mapped[StageState] = mapped_column(
        _enum(StageState, "stage_state"), default=StageState.PENDING, nullable=False)
    translate_state: Mapped[StageState] = mapped_column(
        _enum(StageState, "stage_state"), default=StageState.PENDING, nullable=False)
    validate_state: Mapped[StageState] = mapped_column(
        _enum(StageState, "stage_state"), default=StageState.PENDING, nullable=False)

    #: OCR retries exactly once; extraction retries once. Caps live in config.
    ocr_attempts: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    extract_attempts: Mapped[int] = mapped_column(Integer, default=0, nullable=False)

    overall_state: Mapped[DocumentState] = mapped_column(
        _enum(DocumentState, "document_state"),
        default=DocumentState.PROCESSING, nullable=False)
    #: OCR_P / OCR_F, carried into the CSV.
    processing_status: Mapped[str | None] = mapped_column(String(20))
    failure_reason: Mapped[str | None] = mapped_column(Text)

    # -- PDF validation ---------------------------------------------------
    #
    # Written only after a stage has failed. A document that processed cleanly
    # is never validated: the file demonstrably opened, and re-reading it to
    # confirm that would spend I/O on every document to learn nothing.
    #
    # Columns rather than a separate table: these are facts about one document,
    # read on exactly the screens that already load it, so a join buys nothing.

    #: One of `core.pdf_validation.Status`. NULL means "never validated".
    validation_status: Mapped[str | None] = mapped_column(String(32))
    validation_error_code: Mapped[str | None] = mapped_column(String(48))
    validation_error_message: Mapped[str | None] = mapped_column(Text)
    #: Comma-separated 1-based page numbers ("7,8"). Text rather than an array
    #: so the SQLite fallback behaves identically to PostgreSQL.
    corrupted_pages: Mapped[str | None] = mapped_column(String(500))
    validated_at: Mapped[datetime | None] = mapped_column(TS)
    validator_version: Mapped[str | None] = mapped_column(String(16))
    #: Whether another attempt is worth offering. False for a file that cannot
    #: be opened: a retry fails identically and costs another GPU stage.
    is_retryable: Mapped[bool | None] = mapped_column(Boolean)

    created_at: Mapped[datetime] = mapped_column(TS, server_default=func.now(),
                                                 nullable=False)
    updated_at: Mapped[datetime] = mapped_column(TS, server_default=func.now(),
                                                 onupdate=func.now(), nullable=False)

    batch: Mapped[Batch] = relationship(back_populates="documents")
    # passive_deletes=True: the FKs declare ON DELETE CASCADE, so the database
    # removes children itself. Without this the ORM also issues its own DELETEs
    # and then warns that fewer rows matched than expected, because the cascade
    # already took them. delete-orphan is retained - it is what makes
    # `doc.persons.clear()` in the repositories actually delete rows.
    ocr_pages: Mapped[list[OcrPage]] = relationship(
        back_populates="document", cascade="all, delete-orphan",
        passive_deletes=True)
    extractions: Mapped[list[Extraction]] = relationship(
        back_populates="document", cascade="all, delete-orphan",
        passive_deletes=True)
    property_: Mapped[Property | None] = relationship(
        back_populates="document", cascade="all, delete-orphan", uselist=False,
        passive_deletes=True)
    persons: Mapped[list[Person]] = relationship(
        back_populates="document", cascade="all, delete-orphan",
        passive_deletes=True)
    validations: Mapped[list[ValidationResult]] = relationship(
        back_populates="document", cascade="all, delete-orphan",
        passive_deletes=True)
    #: Append-only diagnosis history. Ordered oldest first so the sequence
    #: reads the way it happened.
    failure_events: Mapped[list[FailureEvent]] = relationship(
        back_populates="document", cascade="all, delete-orphan",
        passive_deletes=True, order_by="FailureEvent.created_at")

    __table_args__ = (
        # A document number must be unique within its batch: this is the guard
        # against duplicate processing after a crash and restart.
        UniqueConstraint("batch_id", "document_id", name="batch_document"),
        Index("ix_documents_batch_overall", "batch_id", "overall_state"),
        # Drives the resume scan on startup.
        Index("ix_documents_resume", "batch_id", "ocr_state", "extract_state",
              "translate_state"),
    )


class OcrPage(Base):
    """Cleaned OCR text, one row per page. Transient - purged after 30 days."""

    __tablename__ = "ocr_pages"

    id: Mapped[int] = mapped_column(BigIntPK, primary_key=True)
    document_id: Mapped[int] = mapped_column(
        ForeignKey("documents.id", ondelete="CASCADE"), nullable=False)
    page_number: Mapped[int] = mapped_column(Integer, nullable=False)
    #: LF line endings only. CRLF changes tokenisation - see ADR-005.
    text: Mapped[str] = mapped_column(Text, nullable=False)
    char_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    #: Indexed because the 30-day expiry sweep filters on it.
    created_at: Mapped[datetime] = mapped_column(TS, server_default=func.now(),
                                                 nullable=False, index=True)

    document: Mapped[Document] = relationship(back_populates="ocr_pages")

    __table_args__ = (
        UniqueConstraint("document_id", "page_number", name="document_page"),
    )


class Extraction(Base):
    """Raw model output plus accounting. Retained for audit."""

    __tablename__ = "extractions"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    document_id: Mapped[int] = mapped_column(
        ForeignKey("documents.id", ondelete="CASCADE"), nullable=False, index=True)
    attempt: Mapped[int] = mapped_column(Integer, default=1, nullable=False)

    raw_output: Mapped[str | None] = mapped_column(Text)
    parsed_ok: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    #: Retry trigger, threshold 0.6.
    pan_coverage: Mapped[float | None] = mapped_column(Numeric(4, 3))
    prompt_tokens: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    completion_tokens: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    #: Hit the token ceiling. On this workload that usually means a repetition
    #: loop, not a long answer, so it is treated as a validation failure.
    truncated: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    model_name: Mapped[str | None] = mapped_column(String(200))
    #: Recorded per extraction because it affects accuracy. Q4_K_M produced a 10x
    #: error on a sale consideration where BF16 was correct; results must be
    #: attributable to a precision.
    quantisation: Mapped[str | None] = mapped_column(String(40))
    prompt_name: Mapped[str | None] = mapped_column(String(100))
    duration_s: Mapped[float | None] = mapped_column(Numeric(10, 3))
    created_at: Mapped[datetime] = mapped_column(TS, server_default=func.now(),
                                                 nullable=False)

    document: Mapped[Document] = relationship(back_populates="extractions")

    __table_args__ = (
        UniqueConstraint("document_id", "attempt", name="document_attempt"),
    )


