# Enumerations
# ---------------------------------------------------------------------------


class BatchState(str, enum.Enum):
    QUEUED = "queued"
    RUNNING = "running"
    PAUSED = "paused"
    COMPLETED = "completed"
    FAILED = "failed"


class StageState(str, enum.Enum):
    PENDING = "pending"
    RUNNING = "running"
    DONE = "done"
    FAILED = "failed"
    SKIPPED = "skipped"


class DocumentState(str, enum.Enum):
    PROCESSING = "processing"
    PROCESSED = "processed"
    FAILED = "failed"
    NEEDS_REVIEW = "needs_review"


class PersonRelation(str, enum.Enum):
    """Matches the CSV's `Transaction Relation (PC)` column exactly."""

    BUYER = "B"
    SELLER = "S"


class BatchMode(str, enum.Enum):
    MANUAL = "manual"
    AUTO = "auto"


def _enum(py_enum: type[enum.Enum], name: str) -> Enum:
    """Native PostgreSQL ENUM, stored by value rather than by Python name."""
    return Enum(py_enum, name=name, native_enum=True,
                values_callable=lambda e: [m.value for m in e])


TS = DateTime(timezone=True)

#: BIGSERIAL on PostgreSQL, plain INTEGER on SQLite. SQLite only auto-increments
#: an `INTEGER PRIMARY KEY` (its rowid alias) - a BIGINT primary key there has no
#: default and inserts fail with a NOT NULL violation. The variant keeps
#: PostgreSQL on 64-bit identifiers while letting the schema be created on SQLite
#: for verification.
BigIntPK = BigInteger().with_variant(Integer, "sqlite")


