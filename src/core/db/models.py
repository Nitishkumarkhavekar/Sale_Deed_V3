"""SQLAlchemy 2.0 declarative models, targeted at PostgreSQL via psycopg v3.

Design constraints these tables exist to satisfy:

1. **Continuous commit.** Every processed document updates the database
   immediately; nothing is deferred to batch end. The app must survive crash,
   shutdown and power loss with no data loss.
2. **Per-stage resume.** Stage state is tracked per *document*, not per batch, so
   a restart never re-runs finished work and never duplicates it.
3. **One CSV row per person.** Stored normalised here; the exporter denormalises.
4. **OCR text is transient.** Purged after 30 days, never backed up. Images are
   never stored - filename, path and metadata only.
5. **Yearly rotation.** Prior year archived to /backup then purged, so every
   large table carries an indexed timestamp to partition on.

Identifier columns (PAN, Aadhaar) are fixed-width **text**, never numeric.
`example.csv` shows what numeric coercion costs: Aadhaars arrived as `6.63E+11`,
irrecoverably.
"""

from __future__ import annotations

import enum
from datetime import date, datetime

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    Enum,
    Float,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


class Base(DeclarativeBase):
    """Declarative base with a consistent naming convention.

    Explicit constraint names matter for Alembic: without them, autogenerated
    migrations produce unnamed constraints that later revisions cannot drop.
    """

    metadata = __import__("sqlalchemy").MetaData(naming_convention={
        "ix": "ix_%(column_0_label)s",
        "uq": "uq_%(table_name)s_%(column_0_name)s",
        "ck": "ck_%(table_name)s_%(constraint_name)s",
        "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
        "pk": "pk_%(table_name)s",
    })


